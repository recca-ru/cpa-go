package cpa

import (
	"context"
	"net/http"
)

const clicksPath = "/cpa/clicks"

// ClicksService — приём переходов по брендированной ссылке интегратора.
type ClicksService service

// Create принимает переход: POST /cpa/clicks.
//
// ⚠⚠ Эта операция НЕ повторяется при сбое, и это главное решение метода. Клик —
// это переход: повтор есть ВТОРОЙ переход, то есть лишний расход капа оффера и
// лишняя строка в статистике партнёра. Ответ мог потеряться уже после того, как
// переход записан, и слепой повтор записал бы его дважды.
//
// Нужна защита от дубля — присылайте ClientClickID: тогда повтор возвращает ТОТ
// ЖЕ клик (200 вместо 201). Это ключ отправителя, и решение о нём принимает
// интегратор, а не клиент за него.
//
// ⚠ Status может приехать ClickTrafficback — переход принят и записан, но к
// рекламодателю не отправлен (исчерпан кап либо не подошло гео). Это НЕ ошибка:
// код ответа успешный, ClickID и RedirectURL при этом законно nil. Клиент,
// считающий успехом только ClickOpen, принял бы штатный ответ за поломку.
func (s *ClicksService) Create(ctx context.Context, params CreateClickParams) (*Click, *Response, error) {
	if err := params.Validate(); err != nil {
		return nil, nil, err
	}

	return do[Click](ctx, (*service)(s), request{
		Method:  http.MethodPost,
		Path:    clicksPath,
		Body:    params,
		Subject: "переход",
		// IdempotentWrite не выставляется НИКОГДА, даже когда прислан
		// ClientClickID: ключ отправителя делает идемпотентной дверь, но
		// договорённости об этом у SDK нет — поле необязательное, и «повторяем,
		// если его прислали» означало бы политику повтора, зависящую от данных
		// вызывающего. Цена ошибки несимметрична: не повторили — потеряли
		// переход, повторили лишний раз — потратили чужой кап.
	})
}
