// # Аутентификация
//
// Ключ арендатора уходит заголовком X-Recca-Tenant-Key и живёт на СЕРВЕРЕ
// интегратора. Он доверенный: один ключ адресует любого партнёра сети
// параметром partner_external_id, и разграничение по людям — работа
// интегратора. Положив ключ во фронтенд, вы отдадите каждому партнёру данные
// всех остальных.
//
// # Ошибки
//
// Отказ двери приезжает как *APIError. Ветвиться нужно по коду — через
// errors.Is с сентинелом, а не сравнением текста: сообщение меняется без
// предупреждения и частью контракта не является.
//
//	if errors.Is(err, cpa.ErrIdempotentMismatch) { … }
//
// Отказ, который клиент дал сам, не обращаясь к двери, несёт cpa.ErrValidation
// и называет поле: отличать его от ответа Recca необходимо, иначе
// интегратор будет искать свой request_id в чужих журналах.
//
// # Границы
//
// Через границу не проходит ни имя, ни почта, ни телефон — ни партнёра, ни его
// клиента. В Recca живут непрозрачные идентификаторы, суммы и факты.
//
// Подпись входящих постбэков проверяет пакет postback, подпись исходящих
// вебхуков — пакет webhook. Сети в них нет: они считают HMAC над тем, что им
// дали.
