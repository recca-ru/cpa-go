// Package cpatypes — типы контракта CPA-API Recca: деньги, идентификаторы,
// параметры запросов и разбор ответов.
//
// Пакет отделён от cpa намеренно и по двум причинам. Первая: он — шов будущей
// генерации из OpenAPI (Н13 эпика), и граница должна быть видна до того, как
// генератор появится. Вторая, практическая: типы нужны и публичному клиенту, и
// внутреннему транспорту, а зависимость «транспорт → cpa» замкнула бы круг.
//
// Источник правды — docs/federation/cpa-api.md и openapi-cpa.yaml в Recca. Всё,
// что здесь названо числом, названо там же.
package cpatypes

// Величины контракта (раздел 5). ⚠ Это КОПИЯ чисел Recca, и копия она
// осознанно: клиент обязан отказывать до сети, а для этого числа должны быть у
// него. Расхождение ловится приёмочным прогоном против песочницы, а не
// компилятором, — предел названный.
const (
	// MaxSumRUB — потолок суммы конверсии, MAX_SUM_RUB.
	MaxSumRUB RUB = 10_000_000
	// MaxExternalIDLen — предел external_id конверсии, MAX_SUB_ID_LENGTH.
	MaxExternalIDLen = 200
	// MaxSubIDLen — предел sub_id, он же MAX_SUB_ID_LENGTH.
	MaxSubIDLen = 200
	// MaxGoalLen — предел кода цели.
	MaxGoalLen = 64
	// MaxPartnerExternalIDLen — предел external_id партнёра, PARTNER_EXTERNAL_ID_MAX.
	MaxPartnerExternalIDLen = 64
	// ReservedExternalIDPrefix — пространство ключей внутренних операций
	// платформы. Занятый нами ключ превратил бы её операцию в идемпотентное
	// попадание, и наоборот, — поэтому граница отбивается, а не переписывается.
	ReservedExternalIDPrefix = "recca:"
)

// Ptr возвращает указатель на значение. Нужен там, где контракт различает «не
// передали» и «передали пустым» (раздел 7): без него три состояния поля
// выражались бы временной переменной на каждый вызов.
func Ptr[T any](v T) *T { return &v }
